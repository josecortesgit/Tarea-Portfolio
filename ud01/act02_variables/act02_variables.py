# age guarda la edad en una variable numérica entera.
# height guarda la altura en una variable numérica decimal.
# is_student guarda si la persona es estudiante usando un valor booleano: True o False.
# print() muestra la información por pantalla.
# La f-string permite introducir directamente las variables dentro del texto usando { }.
